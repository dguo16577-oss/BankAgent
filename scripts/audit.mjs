import YAML from "yaml";
const write = process.argv.includes("--write");
const verbs = ["get", "post", "put", "patch", "delete"];
export const readContract = (name) =>
  YAML.parse(fs.readFileSync(`contracts/openapi/${name}.yaml`, "utf8"));
const files = (dir) =>
  fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((e) =>
      e.isDirectory()
        ? files(path.join(dir, e.name))
        : [path.join(dir, e.name)],
    );
const domain = (p) =>
  p.includes("/auth/") ||
  p.includes("/security/") ||
  p.includes("/demo/sms/") ||
  p.endsWith("/session")
    ? "security"
    : p.includes("/applications") || p.includes("/application-intents")
      ? "applicationrequest"
      : p.includes("time-deposit")
        ? "deposit"
        : p.includes("recurring")
          ? "recurring"
          : p.includes("spending")
            ? "analytics"
            : p.includes("wealth") || p.includes("investment-")
              ? "wealth"
              : p.includes("card")
                ? "card"
                : p.includes("transfer") ||
                    p.includes("recipient") ||
                    p.includes("scheduled-payment")
                  ? "payment"
                  : p.includes("transactions")
                    ? "transaction"
                    : p.includes("accounts")
                      ? "account"
                      : "overview";
const cell = (v) => String(v).replaceAll("|", "\\|").replaceAll("\n", " ");
const table = (headers, rows) =>
  `| ${headers.join(" | ")} |\n| ${headers.map(() => "---").join(" | ")} |\n${rows.map((r) => `| ${r.map(cell).join(" | ")} |`).join("\n")}\n`;
const frozen = {};
const globalIds = new Set();
const operations = {};
for (const surface of ["customer", "public"]) {
  const d = readContract(surface);
  const ops = [];
  for (const [p, v] of Object.entries(d.paths))
    for (const m of verbs) {
      const o = v[m];
      if (!o) continue;
      assert.ok(o.operationId, `${p}: missing operationId`);
      assert.ok(!globalIds.has(o.operationId), `Duplicate ${o.operationId}`);
      globalIds.add(o.operationId);
      assert.ok(p.startsWith(`/${surface}/`));
      if (surface === "customer")
        assert.equal(o["x-session-required"], p !== "/customer/auth/login");
      else assert.deepEqual(o.security ?? d.security, []);
      const idem = (o.parameters ?? []).some(
        (x) => x.in === "header" && x.name === "Idempotency-Key" && x.required,
      );
      ops.push({
        method: m.toUpperCase(),
        path: p,
        operationId: o.operationId,
        auth:
          surface === "public" || p.endsWith("/auth/login")
            ? "No"
            : "Valid session",
        domain: surface === "customer" ? domain(p) : "public-content",
        mutating: m !== "get",
        idempotency: idem,
        request: o.requestBody,
        responses: o.responses,
      });
    }
  operations[surface] = ops;
  // Resolve every local reference, including schema property references.
  function visit(v) {
    if (!v || typeof v !== "object") return;
    if (v.$ref) {
      assert.ok(v.$ref.startsWith("#/"), "External refs are not frozen");
      let target = d;
      for (const part of v.$ref.slice(2).split("/"))
        target = target?.[part.replaceAll("~1", "/").replaceAll("~0", "~")];
      assert.ok(target, `Unresolved ${v.$ref}`);
    }
    if (v.type === "number")
      throw new Error(
        "Floating JSON numbers are not used in these financial contracts",
      );
    Object.values(v).forEach(visit);
  }
  visit(d);
  frozen[surface] = {
    revision: d.info.version,
    sha256: hash(d),
    operations: ops.length,
    schemas: Object.keys(d.components.schemas).length,
    errorCodes:
      d.components.schemas[
        surface === "customer" ? "ApiError" : "PublicApiError"
      ].properties.code.enum.length,
  };
  const manifest =
    `# ${surface} endpoints — M11 freeze\n\nGenerated by \`pnpm audit:update\` from OpenAPI. Revision ${d.info.version}; artifact version, not URL version.\n\n` +
    table(
      [
        "Method",
        "Path",
        "operationId",
        "Authentication",
        "Domain",
        "Mutating?",
        "Idempotency required?",
      ],
      ops.map((o) => [
        o.method,
        `\`${o.path}\``,
        o.operationId,
        o.auth,
        o.domain,
        o.mutating ? "Yes" : "No",
        o.idempotency ? "Yes" : "No",
      ]),
    );
  if (write) fs.writeFileSync(`docs/api/${surface}-endpoints.md`, manifest);
}
const routes = files("apps/web/src/app")
  .filter((f) => /[/\\]page\.tsx$/.test(f))
  .map((f) => {
    const r =
      "/" +
      path
        .relative("apps/web/src/app", path.dirname(f))
        .split(path.sep)
        .filter((s) => s && !s.startsWith("("))
        .join("/");
    return {
      route: r,
      surface: r.startsWith("/app")
        ? "Customer"
        : r === "/login"
          ? "Login"
          : "Public",
      source: f.replaceAll("\\", "/"),
    };
  })
  .sort((a, b) => a.route.localeCompare(b.route));
assert.equal(new Set(routes.map((r) => r.route)).size, routes.length);
for (const r of routes)
  assert.ok(
    !["/overview", "/accounts", "/payments", "/wealth", "/agent"].includes(
      r.route,
    ),
  );
const dependencies = (r) => {
  if (r === "/login") return "/customer/session; /customer/auth/login";
  if (r.startsWith("/app")) {
    const token = r.split("/")[2];
    if (token === "agent-copilot")
      return "Customer session; CopilotKit proxy; Agent v2";
    return (
      {
        overview: "/customer/overview",
        applications:
          "/customer/applications; /customer/applications/*; /public/catalog; /customer/accounts",
        accounts: "/customer/accounts/*",
        transactions: "/customer/transactions/*",
        payments:
          "/customer/recipients; /customer/transfer-intents/*; /customer/transfers/*",
        cards:
          "/customer/cards/*; /customer/card-action-intents/*; /customer/card-actions/*",
        spending: "/customer/spending/summary; /customer/recurring-*",
        wealth: "/customer/wealth/*; /customer/investment-*",
        security: "/customer/auth/step-up-challenges/*",
        agent: "Session only; unavailable feature",
        settings: "Session only; informational placeholder",
      }[token] ?? "/customer/session (redirect)"
    );
  }
  return r === "/"
    ? "/public/home; /public/navigation"
    : r.startsWith("/products") ||
        [
          "/banking",
          "/cards",
          "/cards/compare",
          "/borrowing",
          "/investments",
          "/insurance",
          "/payments-fx",
          "/fees",
        ].includes(r)
      ? "/public/catalog; /public/catalog/{slug}"
      : r.startsWith("/support") || r === "/insights"
        ? "/public/support/articles/*"
        : r === "/ask"
          ? "/public/search"
          : r === "/rates"
            ? "/public/rates"
            : "/public/offers";
};
