const backendPath = "docs/backend/implementation-matrix.md";
const matrixMarker = "## Frozen backend endpoint checklist";
const existingMatrix = fs.existsSync(backendPath)
  ? fs.readFileSync(backendPath, "utf8")
  : "";
const backendHeader = existingMatrix.includes(matrixMarker)
  ? existingMatrix.slice(0, existingMatrix.indexOf(matrixMarker)) +
    matrixMarker +
    "\n\n"
  : "# Backend implementation matrix — M11\n\n";
const statusFile = "docs/backend/implementation-status.json";
const implementationStatus = fs.existsSync(statusFile)
  ? JSON.parse(fs.readFileSync(statusFile, "utf8"))
  : {};
for (const [operationId, status] of Object.entries(implementationStatus)) {
  assert(
    [...operations.customer, ...operations.public].some(
      (operation) => operation.operationId === operationId,
    ),
  );
  assert(
    [
      "NOT_IMPLEMENTED",
      "IMPLEMENTED_IN_MEMORY",
      "IMPLEMENTED_POSTGRESQL",
    ].includes(status),
  );
}
