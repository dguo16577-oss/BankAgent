import assert from "node:assert/strict";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import YAML from "yaml";
import { format, resolveConfig } from "prettier";
const require = createRequire(import.meta.url);
const ts = require("../apps/web/node_modules/typescript");
const directory = "apps/web/src/lib/api";
const found = new Map();
for (const name of readdirSync(directory).filter(
  (n) => n.endsWith(".ts") && !n.includes(".test."),
)) {
  const file = `${directory}/${name}`;
  const source = ts.createSourceFile(
    file,
    readFileSync(file, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  function visit(node) {
    if (
      ts.isCallExpression(node) &&
      ["apiGet", "apiPost"].includes(node.expression.getText(source))
    ) {
      const arg = node.arguments[0];
      let path;
      if (ts.isStringLiteral(arg)) path = arg.text;
      else if (ts.isTemplateExpression(arg)) {
        path = arg.head.text;
        for (const span of arg.templateSpans)
          path +=
            (span.expression.getText(source).startsWith("encodeURIComponent(")
              ? "{id}"
              : "") + span.literal.text;
      }
      assert.ok(path, `Unresolved API call: ${file}`);
      const method =
        node.expression.getText(source) === "apiGet" ? "GET" : "POST";
      found.set(`${method} ${path.split("?")[0]}`, file);
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
}
const rows = [];
for (const scope of ["customer", "public"]) {
  const contract = YAML.parse(
    readFileSync(`contracts/openapi/${scope}.yaml`, "utf8"),
  );
  for (const [path, verbs] of Object.entries(contract.paths))
    for (const method of ["get", "post"]) {
      if (!verbs[method]) continue;
      const key = `${method.toUpperCase()} ${path.replace(/\{[^}]+\}/g, "{id}")}`;
      assert.ok(found.has(key), `Missing typed client: ${key}`);
      rows.push([
        method.toUpperCase(),
        path,
        verbs[method].operationId,
        found.get(key),
      ]);
    }
}
assert.equal(
  found.size,
  rows.length,
  "Unexpected client endpoint outside frozen contract",
);
function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? files(`${dir}/${e.name}`) : [`${dir}/${e.name}`],
  );
}
for (const file of files("apps/web/src").filter(
  (f) =>
    /\.(ts|tsx)$/.test(f) &&
    !/\/(mocks|test|generated)\//.test(f) &&
    !f.includes(".test."),
)) {
  const source = readFileSync(file, "utf8");
  if (file !== "apps/web/src/lib/api/bootstrap.ts")
    assert.ok(
      !/from\s+["'][^"']*mocks|import\(["'][^"']*mocks/.test(source),
      `Production fixture import: ${file}`,
    );
  assert.ok(
    !/(?:localStorage|sessionStorage)\.setItem|indexedDB\.open|persistQueryClient/.test(
      source,
    ),
    `Persistent browser state: ${file}`,
  );
}
const doc = `# M22 typed frontend client audit\n\nGenerated by \`pnpm integration:check\` from frozen contracts and TypeScript call expressions. Customer ${rows.filter((r) => r[1].startsWith("/customer/")).length}/39, Public ${rows.filter((r) => r[1].startsWith("/public/")).length}/9. All calls use the shared transport. Production fixture imports and financial browser persistence are rejected; conditional mock bootstrap is the sole allowed import boundary. Runtime/network evidence remains a separate browser test.\n\n| Method | Frozen path | Operation | Client |\n| --- | --- | --- | --- |\n${rows.map((r) => `| ${r.join(" | ")} |`).join("\n")}\n`;
writeFileSync(
  "docs/frontend/client-integration-audit.md",
  await format(doc, {
    ...(await resolveConfig("docs/frontend/client-integration-audit.md")),
    parser: "markdown",
  }),
);
console.log(
  `Frontend integration audit: ${rows.length}/${rows.length}; no production fixture imports or persistent financial browser cache.`,
);
