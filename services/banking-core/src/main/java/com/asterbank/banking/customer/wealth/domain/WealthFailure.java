package com.asterbank.banking.customer.wealth.domain;

public final class WealthFailure extends RuntimeException {
  public enum Code {
    INVALID_REQUEST,
    INVALID_QUERY,
    PERSISTENCE_UNAVAILABLE,
    INVESTMENT_PRODUCT_NOT_FOUND,
    RISK_PROFILE_NOT_FOUND,
    SUITABILITY_CHECK_NOT_FOUND,
    INVESTMENT_INTENT_NOT_FOUND,
    INVESTMENT_ORDER_NOT_FOUND,
    ACCOUNT_NOT_FOUND,
    RISK_PROFILE_EXPIRED,
    SUITABILITY_CHECK_EXPIRED,
    SUITABILITY_CHECK_MISMATCH,
    INVESTMENT_INTENT_EXPIRED,
    INVESTMENT_INTENT_HASH_MISMATCH,
    INVESTMENT_INTENT_ALREADY_EXECUTED,
    INVESTMENT_INTENT_CANCELLED,
    REDEMPTION_INTENT_NOT_FOUND,
    REDEMPTION_INTENT_EXPIRED,
    REDEMPTION_INTENT_CANCELLED,
    REDEMPTION_INTENT_ALREADY_EXECUTED,
    REDEMPTION_INTENT_HASH_MISMATCH,
    REDEMPTION_EXCEEDS_HOLDING,
    HOLDING_NOT_FOUND,
    INVESTMENT_STATE_CHANGED,
    IDEMPOTENCY_KEY_REUSED,
    INVESTMENT_PRODUCT_UNAVAILABLE,
    PRODUCT_NOT_SUITABLE,
    INVESTMENT_AMOUNT_BELOW_MINIMUM,
    INSUFFICIENT_FUNDS,
    CURRENCY_MISMATCH,
    INVALID_AMOUNT,
    ACCOUNT_NOT_ELIGIBLE
  }

  private final Code code;

  public WealthFailure(Code code) {
    super(code.name());
    this.code = code;
  }

  public Code code() {
    return code;
  }
}
