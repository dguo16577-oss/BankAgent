package com.asterbank.banking.customer.payment.application;

/** Business failure categories, mapped to frozen HTTP errors only at the web boundary. */
public final class PaymentFailure extends RuntimeException {
  public enum Code {
    SCHEDULE_NOT_FOUND,
    SCHEDULE_STATE_CHANGED,
    SCHEDULE_ALREADY_DUE,
    INVALID_SCHEDULE_TIME,
    SCHEDULE_INTENT_NOT_FOUND,
    SCHEDULE_INTENT_HASH_MISMATCH,
    SCHEDULE_INTENT_UNAVAILABLE,
    SCHEDULE_TERMS_INVALID,
    SPLIT_NOT_FOUND,
    SPLIT_INTENT_NOT_FOUND,
    SPLIT_RECIPIENT_UNAVAILABLE,
    SPLIT_STATE_CHANGED,
    SPLIT_INTENT_UNAVAILABLE,
    SPLIT_INTENT_HASH_MISMATCH,
    ACCOUNT_NOT_FOUND,
    RECIPIENT_NOT_FOUND,
    RECIPIENT_INACTIVE,
    RECIPIENT_ALREADY_EXISTS,
    RECIPIENT_STATE_CHANGED,
    RECIPIENT_INTENT_NOT_FOUND,
    RECIPIENT_INTENT_EXPIRED,
    RECIPIENT_INTENT_ALREADY_EXECUTED,
    RECIPIENT_INTENT_HASH_MISMATCH,
    TRANSFER_SESSION_MISMATCH,
    INVALID_DESTINATION,
    TRANSFER_INTENT_NOT_FOUND,
    TRANSFER_NOT_FOUND,
    ACCOUNT_NOT_ELIGIBLE,
    RECIPIENT_NOT_ELIGIBLE,
    INVALID_AMOUNT,
    CURRENCY_MISMATCH,
    INSUFFICIENT_FUNDS,
    INVALID_REQUEST,
    INVALID_QUERY,
    TRANSFER_INTENT_HASH_MISMATCH,
    TRANSFER_INTENT_ALREADY_EXECUTED,
    TRANSFER_INTENT_EXPIRED,
    TRANSFER_INTENT_CANCELLED,
    IDEMPOTENCY_KEY_REUSED,
    PERSISTENCE_UNAVAILABLE
  }

  private final Code code;

  public PaymentFailure(Code code) {
    super(code.name());
    this.code = code;
  }

  public Code code() {
    return code;
  }
}
