package com.asterbank.banking.security.domain;

public enum VerificationAction {
  LOGIN,
  RECIPIENT_CREATE,
  RECIPIENT_DEACTIVATE,
  TRANSFER_EXECUTE,
  SCHEDULED_PAYMENT_CREATE,
  SCHEDULED_PAYMENT_MODIFY,
  SCHEDULED_PAYMENT_CANCEL,
  SPLIT_REQUEST_CREATE,
  SPLIT_REQUEST_CANCEL,
  CARD_FREEZE,
  CARD_UNFREEZE,
  CARD_CONTROL_RISK_INCREASING,
  CARD_CONTROL_PROTECTIVE,
  INVESTMENT_ORDER_EXECUTE,
  RECURRING_STOP_FUTURE_PAYMENTS,
  CARD_APPLICATION_SUBMIT,
  CREDIT_LIMIT_APPLICATION_SUBMIT,
  LOAN_APPLICATION_SUBMIT,
  PRODUCT_APPLICATION_SUBMIT;

  public String resourceType() {
    return switch (this) {
      case LOGIN -> "LOGIN";
      case RECIPIENT_CREATE, RECIPIENT_DEACTIVATE -> "RECIPIENT_ACTION_INTENT";
      case TRANSFER_EXECUTE -> "TRANSFER_INTENT";
      case SCHEDULED_PAYMENT_CREATE, SCHEDULED_PAYMENT_MODIFY, SCHEDULED_PAYMENT_CANCEL ->
          "SCHEDULE_ACTION_INTENT";
      case SPLIT_REQUEST_CREATE, SPLIT_REQUEST_CANCEL -> "SPLIT_ACTION_INTENT";
      case CARD_FREEZE, CARD_UNFREEZE, CARD_CONTROL_RISK_INCREASING, CARD_CONTROL_PROTECTIVE ->
          "CARD_ACTION_INTENT";
      case CREDIT_LIMIT_APPLICATION_SUBMIT -> "CREDIT_LIMIT_INTENT";
      case INVESTMENT_ORDER_EXECUTE -> "INVESTMENT_ORDER_INTENT";
      case RECURRING_STOP_FUTURE_PAYMENTS -> "RECURRING_PAYMENT_INTENT";
      case CARD_APPLICATION_SUBMIT, LOAN_APPLICATION_SUBMIT, PRODUCT_APPLICATION_SUBMIT ->
          "APPLICATION_INTENT";
    };
  }
}
