import { describe, expect, it } from "vitest";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { getService, serviceCatalog } from "./service-catalog";
import { parsePresentation } from "./presentation-schema";

describe("trusted rich presentation", () => {
  it("maps only known service identifiers to audited routes", () => {
    expect(getService("transfer")?.href).toBe("/app/payments");
    expect(getService("https://evil.example")).toBeUndefined();
    expect(getService("toString")).toBeUndefined();
    expect(
      parsePresentation([
        { kind: "SERVICE_CARD", service_id: "transfer" },
        { kind: "SERVICE_CARD", service_id: "https://evil.example" },
      ]),
    ).toHaveLength(1);
  });

  it("every catalog route has an actual Next.js page", () => {
    for (const service of Object.values(serviceCatalog)) {
      expect(
        existsSync(join(process.cwd(), "src", "app", service.href, "page.tsx")),
      ).toBe(true);
    }
  });

  it("rejects model-like amounts and oversized tables", () => {
    const base = {
      kind: "SUMMARY_CARD",
      title: "Spending",
      currency: "CNY",
      date_range: { from: "2026-10-01", to: "2026-11-01" },
      incomplete: false,
      source: "summarize_spending",
    };
    expect(parsePresentation([{ ...base, amount: "100.00" }])).toHaveLength(1);
    expect(
      parsePresentation([{ ...base, amount: "¥100 generated by model" }]),
    ).toHaveLength(0);
    expect(
      parsePresentation([
        {
          kind: "TABLE",
          title: "Rows",
          source: "list_transactions",
          columns: [{ key: "amount", label: "Amount" }],
          rows: Array.from({ length: 51 }, () => ({ amount: "1.00" })),
          incomplete: false,
        },
      ]),
    ).toHaveLength(0);
  });
});
